import { execFileSync } from 'node:child_process'
import { mkdir, readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const packageJson = JSON.parse(await readFile(resolve(repositoryRoot, 'package.json'), 'utf8'))
const outputPath = resolve(repositoryRoot, 'src/generated/build-identity.ts')
const temporaryPath = `${outputPath}.${process.pid}.tmp`

function git(args, fallback) {
  try {
    return execFileSync('git', args, {
      cwd: repositoryRoot,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore']
    }).trim()
  } catch {
    return fallback
  }
}

function releaseChannel(version) {
  if (process.env.KNM_RELEASE_CHANNEL) return process.env.KNM_RELEASE_CHANNEL
  if (version.includes('-dev.')) return 'development'
  if (version.includes('-')) return 'prerelease'
  return 'stable'
}

const identity = {
  productName: 'Koinos Node Manager',
  productVersion: packageJson.version,
  interfaceName: 'cli',
  interfaceVersion: '1',
  coreVersion: packageJson.version,
  gitCommit: process.env.KNM_GIT_COMMIT ?? git(['rev-parse', 'HEAD'], 'unknown'),
  releaseChannel: releaseChannel(packageJson.version),
  buildTimestamp: process.env.KNM_BUILD_TIMESTAMP ?? new Date().toISOString(),
  sourceState: git(['status', '--porcelain', '--untracked-files=normal'], '') === '' ? 'clean' : 'dirty'
}

const source = `// Generated by scripts/generate-build-identity.mjs. Do not edit.\n\n` +
  `export const generatedBuildIdentity = Object.freeze(${JSON.stringify(identity, null, 2)} as const)\n`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(temporaryPath, source, { encoding: 'utf8', mode: 0o600 })
await rename(temporaryPath, outputPath)
